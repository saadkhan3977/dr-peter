            let currentQuantity = parseInt($input.val()) || 1;

            let newQuantity = currentQuantity;
            console.log("Current Quantity:", currentQuantity);

            if ($button.hasClass('btn-plus')) {
                newQuantity + 1;
            } else if ($button.hasClass('btn-minus')) {
                newQuantity = currentQuantity > 1 ? currentQuantity :
                    1;
            }

            console.log("Updated Quantity:", newQuantity);

            $input.val(newQuantity);

            let cartId = $button.data('id');
            let form = $(`#cart-update-form-${cartId}`);

            form.find('input[name="quantity"]').val(newQuantity);

            $.ajax({
                url: form.attr('action'),
                method: form.attr('method'),
                data: form.serialize(),
                success: function(response) {
					if(response.status == 'success')
					{
						alert('cart add successfully');
					}

                    // Check if response contains new_quantity, total_price, and grandtotal
                    if (response.new_quantity && response.total_price && response.grandtotal) {
                        // Update the quantity input field with the new quantity
                        $input.val(response.new_quantity);

                        // Update the total price for the item (replace text in the correct DOM element)
                        $(`#total-price-${cartId}`).text(response.total_price);

                        // Update the grand total (replace text in the correct DOM element)
                        $('#grandtotal').text(response.grandtotal);
                    } else {
                        console.warn("Response is missing expected values.");
                    }
                },
                error: function(xhr) {
                    console.error("Error Response:", xhr.responseJSON);
                    alert(xhr.responseJSON.message || "An error occurred while updating the cart.");
                }
            });
        });
